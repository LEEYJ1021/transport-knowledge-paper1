# ## 전체 논리
# 기존 "신생/쇠퇴"는 토픽 비중의 단순 증감이었습니다. S4는 이것을 세 축으로 다시 정의합니다.
# 1. **양:** 얼마나 변했는가
# 2. **질:** 변한 토픽이 영향력 있는 논문으로 이뤄졌는가
# 3. **구성:** 그 변화가 저널 안에서 일어났는가, 저널 비중이 바뀐 탓인가
