# ## 결론

# **풀 재표집 바닥으로 바꾸자 보정값이 대부분 양수로 바뀌었습니다.** `all`에서 22/25 연도가 양수이고 15개 연도가 p<0.05입니다. 이전의 "전부 음수"는 반분 바닥이 인접 연도 비교의 잡음을 과대평가한 결과였고(제가 추정했던 방향과 일치), 연 단위 탐지가 가능합니다. 다만 아래 주의가 있습니다.

