# ## 4.3 질 (실행 완료)
# - **정의:** 연도×저널 셀 안의 평균 순위 백분위 `(rank−0.5)/n`입니다. 2023년 이후 논문은 제외합니다(인용 누적 부족).
# - **토픽 지표:** 평균 백분위, 상위 10% 비율, 논문 부트스트랩(B=1000) 95% 구간입니다.
